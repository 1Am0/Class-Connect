// Rebuilds lib/i18n/<language>/index.ts from the namespace files in each
// language folder. Run after adding a namespace: node scripts/i18n-index.mjs
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../lib/i18n/", import.meta.url).pathname;
const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const english = readdirSync(join(root, "en"))
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .map((file) => file.slice(0, -3))
  .sort();

for (const language of readdirSync(root, { withFileTypes: true })) {
  if (!language.isDirectory()) continue;
  const dir = join(root, language.name);
  // Language folders hold common.ts; others (help/) are not text packs.
  if (!existsSync(join(dir, "common.ts"))) continue;
  const names = english.filter((name) => existsSync(join(dir, `${name}.ts`)));
  const imports = names
    .map((name) => `import ${camel(name)} from "./${name}";`)
    .join("\n");
  const type =
    language.name === "en"
      ? ""
      : language.name === "es"
        ? `import type { CompletePack } from "../catalog";\n`
        : `import type { LanguagePack } from "../catalog";\n`;
  const annotation =
    language.name === "en"
      ? ""
      : language.name === "es"
        ? ": CompletePack"
        : ": LanguagePack";
  writeFileSync(
    join(dir, "index.ts"),
    `// Generated by scripts/i18n-index.mjs.\n${type}${imports}\n\nexport const ${language.name}${annotation} = {\n${names
      .map((name) => `  ${camel(name)},`)
      .join("\n")}\n};\n`,
  );
}
